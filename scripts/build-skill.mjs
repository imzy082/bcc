/**
 * 构建自包含 skill：小型 CJS 入口 + 分块 ESM 运行时，全量内联 JS 依赖。
 * 分割根仅用于划分共享依赖边界；只发布从 CLI 可达的输出文件。
 * ffmpeg/ffprobe 二进制仍由运行时解析/下载，不需要用户安装 npm 依赖。
 */
import esbuild from 'esbuild'
import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs'
import { basename, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeThirdPartyNotices } from './third-party-notices.mjs'

const pkg = JSON.parse(readFileSync('package.json', 'utf-8'))
const outdir = resolve('skills/bcc/bin')
const entryPoints = { 'bcc-main': 'apps/bcc-cli/src/index.ts' }
// 显式分出较大的 SDK、导出库及它们的共享依赖，避免单个共享块重新膨胀。
// 使用 import 条件解析，避免同一依赖的 CJS/ESM 两套实现被重复打包。
const splitRoots = [
  'undici', '@google/genai', 'docx', 'exceljs', '@anthropic-ai/sdk',
  'google-auth-library', 'web-streams-polyfill', 'bluebird', 'jszip', 'pako',
  'ws', 'unzipper', 'archiver',
]
for (const name of splitRoots) {
  entryPoints[`vendor-${name.replace(/[@/]/g, '-')}`] = fileURLToPath(import.meta.resolve(name))
}

const result = await esbuild.build({
  entryPoints,
  outdir,
  write: false,
  bundle: true,
  splitting: true,
  metafile: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outExtension: { '.js': '.mjs' },
  chunkNames: 'bcc-chunk-[hash]',
  minify: true,
  keepNames: true,
  lineLimit: 160,
  // CJS 依赖仍可能动态 require Node 内置模块或引用 __dirname/__filename。
  // 所有块与入口同目录，保持原单文件的相对资源查找基准。
  banner: {
    js: `// Generated by scripts/build-skill.mjs; edit TypeScript sources, not this file.
import { createRequire as __bccCreateRequire } from 'node:module';
import { fileURLToPath as __bccFileURLToPath } from 'node:url';
import { dirname as __bccDirname } from 'node:path';
const require = __bccCreateRequire(import.meta.url);
const __filename = __bccFileURLToPath(import.meta.url);
const __dirname = __bccDirname(__filename);`,
  },
  alias: {
    '@shared': resolve('packages/bcc-core/src/shared'),
    '@core': resolve('packages/bcc-core/src'),
  },
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  logLevel: 'silent',
})

const outputs = result.metafile.outputs
const entry = Object.keys(outputs).find((name) => basename(name) === 'bcc-main.mjs')
if (!entry) throw new Error('Missing skill entry output')
const reachable = new Set()
function visit(name) {
  if (reachable.has(name)) return
  if (!outputs[name]) throw new Error(`Missing skill chunk: ${name}`)
  reachable.add(name)
  for (const imported of outputs[name].imports) {
    if (!imported.external) visit(imported.path)
  }
}
visit(entry)
// 不发布额外的 vendor 入口，只保留真正被 CLI 引用的代码块。
const runtimeOutputs = Object.fromEntries([...reachable].map((name) => [name, outputs[name]]))
const maxBytes = 512 * 1024
for (const [name, output] of Object.entries(runtimeOutputs)) {
  if (output.bytes > maxBytes) {
    throw new Error(`${name} exceeds the 512 KiB skill chunk budget; adjust splitRoots before publishing`)
  }
}
const noticeCount = writeThirdPartyNotices({ ...result.metafile, outputs: runtimeOutputs })
const keep = new Set([...reachable].map((name) => resolve(name)))
mkdirSync(outdir, { recursive: true })
for (const output of result.outputFiles) {
  if (keep.has(output.path)) writeFileSync(output.path, output.contents)
}
const launcher = `#!/usr/bin/env node
// Generated entry. Deploy the entire bin/ directory; edit TypeScript sources and rebuild.
import('./bcc-main.mjs').catch((error) => {
  console.error('失败: 无法启动 bcc，请确认 bin/ 目录完整。', error.message);
  process.exitCode = 1;
});
`
writeFileSync(resolve(outdir, 'bcc.cjs'), launcher)
// 只清理本构建拥有的旧块；不删除用户自行放入 bin/ 的其他文件。
for (const name of readdirSync(outdir)) {
  if (/^bcc-(?:main|chunk-[A-Z0-9]+)\.mjs$/.test(name) && !keep.has(resolve(outdir, name))) {
    unlinkSync(resolve(outdir, name))
  }
}
const total = Object.values(runtimeOutputs).reduce((n, output) => n + output.bytes, Buffer.byteLength(launcher))
console.log(`[build-skill] 已保留 ${noticeCount} 个内联依赖的许可通知`)
console.log(`[build-skill] ${reachable.size + 1} 个自包含运行文件，总计 ${total} 字节，最大块 ${Math.max(...Object.values(runtimeOutputs).map((o) => o.bytes))} 字节`)
console.log('[build-skill] 使用 node skills/bcc/bin/bcc.cjs；提交与部署完整 bin/ 目录')
